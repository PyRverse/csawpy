# Generate actual csaw/edgeR reference outputs. Install dependencies separately.
# Configure R_LIBS_USER for your reference environment; no R runtime is needed
# when using csawpy or running the ordinary Python test suite.
args <- commandArgs(trailingOnly=TRUE)
outdir <- if(length(args)) args[1] else 'reference'
dir.create(outdir, recursive=TRUE, showWarnings=FALSE)
suppressPackageStartupMessages({library(csaw); library(edgeR); library(jsonlite)})
set.seed(20261022)
lib <- c(800000,1200000,900000,1100000,850000,1150000,950000,1050000)
condition <- rep(c(0,1), each=4)
base <- exp(runif(100, log(20), log(300)))
effect <- c(rep(log(2), 15), rep(-log(2),15),rep(0,70))
mu <- exp(log(base) + effect %o% condition) * rep(lib / mean(lib), each=100)
y <- matrix(rnbinom(length(mu), mu=as.vector(mu), size=1/0.15), nrow=100)
x <- cbind(1, condition)
run_case <- function(name, counts, design, contrast, dispersion) {
  fit <- glmQLFit(counts, design=design, dispersion=dispersion,
    offset=log(lib), legacy=TRUE, robust=FALSE, abundance.trend=FALSE,
    prior.count=0)
  tested <- glmQLFTest(fit, contrast=contrast, poisson.bound=TRUE)
  expected <- data.frame(tested$table, deviance=fit$deviance,
    ql_posterior=fit$s2.post, prior_df=fit$df.prior,
    prior_variance=fit$s2.prior, df_residual=fit$df.residual.zeros,
    df_total=tested$df.total)
  expected$FDR <- p.adjust(expected$PValue, 'BH')
  write.csv(expected, file.path(outdir,paste0(name,'-expected.csv')), row.names=FALSE)
  write_json(list(counts=unname(counts), design=unname(design), contrast=contrast,
    library_sizes=lib, dispersion=dispersion), file.path(outdir,paste0(name,'-input.json')),
    auto_unbox=TRUE, digits=17, pretty=TRUE, matrix='rowmajor')
}
run_case('two-group', y, x, c(0,1), 0.15)
xc <- cbind(x, c(-1.4,0.6,1.2,-0.4,0.4,-1.1,1.4,-0.7))
run_case('covariate', y, xc, c(0,1,0), 0.15)
yz <- y
yz[1,] <- 0
yz[2,1:4] <- 0
run_case('zeros', yz, x, c(0,1), 0.15)
common <- dispCoxReid(y, design=x, offset=log(lib), subset=NULL)
run_case('estimated', y, x, c(0,1), common)
factors <- calcNormFactors(y, lib.size=lib, method='TMM')
write_json(list(tmm=factors, common_dispersion=common), file.path(outdir,'normalization.json'),
  auto_unbox=TRUE, pretty=TRUE, digits=17)
windows <- data.frame(chrom=c('chr1','chr1','chr1','chr2','chr1'),
  start=c(100,0,400,0,150), end=c(200,100,500,100,250))
gr <- GRanges(windows$chrom, IRanges(windows$start+1, windows$end))
merged <- mergeWindows(gr, tol=50)
p <- c(.001,.02,.9,.04,.4)
combined <- combineTests(merged$ids, data.frame(logFC=c(2,1,0,-1,0),PValue=p))
regions <- as.data.frame(merged$regions)[,c('seqnames','start','end')]
regions$start <- regions$start-1
names(regions)[1] <- 'chrom'
write_json(list(windows=windows, ids=merged$ids, regions=regions,
  pvalues=p, combined=as.data.frame(combined)[,c('num.tests','PValue','FDR')]),
  file.path(outdir,'regions.json'),auto_unbox=TRUE,pretty=TRUE,digits=17)
frags <- data.frame(chrom=c('chr1','chr1','chr1','chr2'),start=c(0,90,200,50),end=c(10,110,210,150))
fg <- GRanges(frags$chrom, IRanges(frags$start+1,frags$end))
write_json(list(windows=windows, fragments=frags, counts=countOverlaps(gr,fg)),
  file.path(outdir,'overlaps.json'),auto_unbox=TRUE,pretty=TRUE,digits=17)
pkgs <- c('csaw','edgeR','limma','metapod','GenomicRanges','jsonlite')
write_json(list(generated_utc=format(Sys.time(),tz='UTC',usetz=TRUE),
  R=R.version.string, packages=as.list(setNames(vapply(pkgs,function(p) as.character(packageVersion(p)),''),pkgs)),
  seed=20261022, settings=list(legacy=TRUE,robust=FALSE,abundance_trend=FALSE,prior_count=0,
  poisson_bound=TRUE), data='Synthetic; generated by this script, no patient data.'),
  file.path(outdir,'provenance.json'),pretty=TRUE,auto_unbox=TRUE)
